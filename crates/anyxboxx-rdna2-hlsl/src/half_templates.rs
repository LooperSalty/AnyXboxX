//! Operand widths and HLSL expressions for half-precision vector operations.
pub(super) fn operation(name: &str) -> Option<(&'static str, &'static str)> {
    Some(match name {
        "v_add_f16" => ("hh", "F16Add({a}, {b})"),
        "v_sub_f16" => ("hh", "F16Sub({a}, {b})"),
        "v_subrev_f16" => ("hh", "F16Sub({b}, {a})"),
        "v_mul_f16" => ("hh", "F16Mul({a}, {b})"),
        "v_fmac_f16" => ("hh", "F16Fma({a}, {b}, {d})"),
        "v_fmamk_f16" => ("hh", "F16Fma({a}, {k}, {b})"),
        "v_fmaak_f16" => ("hh", "F16Fma({a}, {b}, {k})"),
        "v_fma_f16" => ("hhh", "F16Fma({a}, {b}, {c})"),
        "v_max_f16" => ("hh", "F16Max({a}, {b})"),
        "v_min_f16" => ("hh", "F16Min({a}, {b})"),
        "v_ldexp_f16" => ("hi", "F16Ldexp({a}, {b})"),
        "v_cvt_f16_f32" => ("w", "F32ToF16({a})"),
        "v_cvt_f32_f16" => ("h", "F16ToF32({a})"),
        "v_floor_f16" => ("h", "F32ToF16(asuint(floor(asfloat(F16ToF32({a})))))"),
        "v_ceil_f16" => ("h", "F32ToF16(asuint(ceil(asfloat(F16ToF32({a})))))"),
        "v_trunc_f16" => ("h", "F32ToF16(asuint(trunc(asfloat(F16ToF32({a})))))"),
        "v_rndne_f16" => ("h", "F16Rndne({a})"),
        "v_rcp_f16" => ("h", "F16Rcp({a})"),
        "v_sqrt_f16" => ("h", "F16Sqrt({a})"),
        "v_rsq_f16" => ("h", "F16Rsq({a})"),
        "v_log_f16" => ("h", "F16Log({a})"),
        "v_exp_f16" => ("h", "F16Exp({a})"),
        "v_sin_f16" => ("h", "F16Trig({a}, false)"),
        "v_cos_f16" => ("h", "F16Trig({a}, true)"),
        "v_cvt_f16_u16" => ("i", "F32ToF16(asuint((float){a}))"),
        "v_cvt_f16_i16" => ("i", "F32ToF16(asuint((float)(asint({a} << 16) >> 16)))"),
        "v_cvt_u16_f16" => ("h", "F16ToU16({a})"),
        "v_cvt_i16_f16" => ("h", "F16ToI16({a})"),
        "v_cvt_norm_i16_f16" => ("h", "F16Norm({a}, 32767u, true)"),
        "v_cvt_norm_u16_f16" => ("h", "F16Norm({a}, 65535u, false)"),
        "v_cvt_pknorm_i16_f16" => (
            "hh",
            "(F16Norm({b}, 32767u, true) << 16 | F16Norm({a}, 32767u, true))",
        ),
        "v_cvt_pknorm_u16_f16" => (
            "hh",
            "(F16Norm({b}, 65535u, false) << 16 | F16Norm({a}, 65535u, false))",
        ),
        "v_cvt_pknorm_i16_f32" => (
            "ww",
            "(F32Norm16({b}, 32767u, true) << 16 | F32Norm16({a}, 32767u, true))",
        ),
        "v_cvt_pknorm_u16_f32" => (
            "ww",
            "(F32Norm16({b}, 65535u, false) << 16 | F32Norm16({a}, 65535u, false))",
        ),
        "v_pack_b32_f16" => ("hh", "({b} << 16 | {a})"),
        "v_min3_f16" => ("hhh", "F16Min(F16Min({a}, {b}), {c})"),
        "v_max3_f16" => ("hhh", "F16Max(F16Max({a}, {b}), {c})"),
        "v_med3_f16" => ("hhh", "F16Med3({a}, {b}, {c})"),
        _ => return None,
    })
}
