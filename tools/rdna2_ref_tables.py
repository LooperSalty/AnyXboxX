"""Écrit les tables de crates/anyxboxx-rdna2-ref depuis les données Python de l'interpréteur de référence.

Sources : PrototypeScarlett/emu/rdna2_ops.py (mnémoniques par famille et opcode, tirés des tests
d'encodage de LLVM par tools/rdna2_mnemonics.py) ; emu/data/gfx10_formats.json (noms des formats,
rdna2_image.FORMAT_NAMES) et rdna2_buffer_format.FORMATS (formats des accès typés). Sorties :
crates/anyxboxx-rdna2-ref/src/mnemonics.rs (une fonction `mnemonic(family, opcode)`) et
src/format_table.rs (FORMAT_NAMES, BUFFER_FORMATS). Les fichiers générés ne sont pas modifiés à la
main ; relancer ce script après toute mise à jour de ces sources :

    py -3.12 tools/rdna2_ref_tables.py
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "PrototypeScarlett"))
OUTPUT = ROOT / "crates" / "anyxboxx-rdna2-ref" / "src" / "mnemonics.rs"
FORMAT_OUTPUT = OUTPUT.with_name("format_table.rs")
KIND_VARIANTS = {1: "Unorm", 2: "Snorm", 3: "Uscaled", 4: "Sscaled", 5: "Uint", 6: "Sint", 7: "Float"}


def render(mnemonics):
    lines = [
        "//! Mnémoniques RDNA 2 par (famille, opcode). Généré par tools/rdna2_ref_tables.py depuis",
        "//! PrototypeScarlett/emu/rdna2_ops.py (tests d'encodage de LLVM). Ne pas modifier.",
        "",
        "/// Le nom de l'instruction de cet encodage, si les tests de LLVM le donnent.",
        "pub fn mnemonic(family: &str, opcode: u32) -> Option<&'static str> {",
        "    let name = match (family, opcode) {",
    ]
    for (family, opcode), name in sorted(mnemonics.items()):
        lines.append(f'        ("{family}", 0x{opcode:03X}) => "{name}",')
    lines += ["        _ => return None,", "    };", "    Some(name)", "}", ""]
    return "\n".join(lines)


def render_formats(names, formats):
    """format_table.rs : les noms des formats gfx10 et les formats des accès typés aux buffers."""
    lines = [
        "//! GFX10 unified format names and the formats of typed buffer accesses. Generated by",
        "//! tools/rdna2_ref_tables.py from PrototypeScarlett/emu/data/gfx10_formats.json",
        "//! (`rdna2_image.FORMAT_NAMES`) and `rdna2_buffer_format.FORMATS`. Do not edit.",
        "",
        "use crate::buffer_format::{Format, Kind};",
        "",
        "/// The name of each format code of `gfx10_formats.json`, in code order.",
        f"pub const FORMAT_NAMES: [(u32, &str); {len(names)}] = [",
    ]
    lines += [f'    ({code}, "{name}"),' for code, name in sorted(names.items())]
    lines += ["];", "", "/// The formats a typed buffer access reads (and, when `storable`, writes), in code order.",
              "#[rustfmt::skip]", f"pub const BUFFER_FORMATS: [Format; {len(formats)}] = ["]
    for code, found in sorted(formats.items()):
        widths = ", ".join(str(width) for width in found.widths)
        lines.append(f"    Format {{ code: {code}, kind: Kind::{KIND_VARIANTS[found.kind]}, widths: &[{widths}], "
                     f"size: {found.size}, align: {found.align} }},")
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    from emu.rdna2_buffer_format import FORMATS
    from emu.rdna2_image import FORMAT_NAMES
    from emu.rdna2_ops import MNEMONICS

    OUTPUT.write_text(render(MNEMONICS), encoding="utf-8")
    print(f"{len(MNEMONICS)} mnémoniques -> {OUTPUT}")
    FORMAT_OUTPUT.write_text(render_formats(FORMAT_NAMES, FORMATS), encoding="utf-8")
    print(f"{len(FORMAT_NAMES)} noms de formats, {len(FORMATS)} formats de buffer -> {FORMAT_OUTPUT}")


if __name__ == "__main__":
    main()
